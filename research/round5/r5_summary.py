"""Round 5 tables from scores/<set>/<item>.json (r5_score.py).   r5_summary.py [score root] > tables.md
Per stem: mean uSDR over the items that have the part, paired delta vs hyb6 with a 95 % bootstrap interval over items
(2000 resamples, seed 0, as round 4) and items improved; "removed" uSDR over all items; sum-to-mix residual per recipe;
the estimate's level on items without the part (leak); per-set means; per-item uSDR.
"""
import glob, json, os, sys
import numpy as np

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'scores')
SETS = {'cmt8': 'Cambridge-MT: 8 MUSDB test songs (90 s each)', 'cmtx': 'Cambridge-MT: 18 non-MUSDB rock excerpts'}
STEMS = ('vocals', 'drums', 'bass', 'guitar', 'keys', 'other')
ORDER = ['hyb6', 'hyb6_fix', 'chain', 'chain_fix', 'mega_mix', 'mega_mix_keys', 'mega_mix_pk', 'mega_mix_kb5',
         'mega_mix_lb', 'mega_mix_lb_pk', 'kim_mega', 'kim_mega_keys', 'kim_mega_pk', 'kim_mega_kb5', 'chain+mg', 'chain+mgk']
# variants whose stem is identical to another's (only "other" differs) are shown once per stem
SAME = {'vocals': {'hyb6_fix': 'hyb6', 'chain_fix': 'chain', 'mega_mix_keys': 'mega_mix', 'mega_mix_pk': 'mega_mix', 'mega_mix_kb5': 'mega_mix',
                   'mega_mix_lb_pk': 'mega_mix_lb', 'kim_mega_keys': 'kim_mega', 'kim_mega_pk': 'kim_mega', 'kim_mega_kb5': 'kim_mega',
                   'chain+mg': 'chain', 'chain+mgk': 'chain'}}
for k in ('drums', 'bass', 'guitar'):
    SAME[k] = dict(SAME['vocals']); SAME[k].update({'mega_mix_lb': 'mega_mix', 'chain+mg': 'kim_mega', 'chain+mgk': 'kim_mega'})
for k in ('drums', 'bass'): SAME[k].update({'chain+mg': 'chain', 'chain+mgk': 'chain'})
SAME['keys'] = {'hyb6_fix': 'hyb6', 'chain_fix': 'chain', 'mega_mix_lb': 'mega_mix', 'mega_mix_lb_pk': 'mega_mix_pk', 'chain+mg': 'chain',
                'chain+mgk': 'kim_mega'}
SAME['other'] = {}
rng = np.random.default_rng(0)

def boot(x):
    if len(x) < 2: return (np.nan, np.nan)
    m = [rng.choice(x, len(x)).mean() for _ in range(2000)]; return np.percentile(m, [2.5, 97.5])

def load(s):
    return {f'{s}/{os.path.basename(f)[:-5]}': json.load(open(f)) for f in sorted(glob.glob(f'{root}/{s}/*.json'))}

data = {s: load(s) for s in SETS}
ALL = {k: v for s in SETS for k, v in data[s].items()}
vs = [v for v in ORDER if ALL and all(v in d for d in ALL.values())]
f2 = lambda x: '–' if x is None or (isinstance(x, float) and np.isnan(x)) else f'{x:.2f}'

def delta(D, v, k, key, base='hyb6'):
    items = [i for i, d in D.items() if d[v][k][key] is not None and d[base][k][key] is not None]
    dl = np.array([D[i][v][k][key] - D[i][base][k][key] for i in items])
    if v == base or not len(dl): return '–', dl
    if not np.any(dl): return 'same stem', dl
    lo, hi = boot(dl); return f'{dl.mean():+.2f} [{lo:+.2f}, {hi:+.2f}] {int((dl > 0).sum())}/{len(dl)}', dl

def table(D, title):
    secs = sum(d['_meta']['seconds'] for d in D.values())
    print(f'## {title} ({len(D)} items, {secs / 60:.1f} min)\n')
    for k in STEMS:
        n = sum(k in d['_meta']['has'] for d in D.values())
        print(f'### {k} ({n} items have it)\n')
        print('| variant | uSDR | Δ vs hyb6 [95 % CI] items up | removed uSDR (all items) | Δ removed vs hyb6 | level on items without it (dB re mix) |')
        print('|---|---|---|---|---|---|')
        for v in vs:
            if v in SAME.get(k, {}): continue
            u = [d[v][k]['usdr'] for d in D.values() if d[v][k]['usdr'] is not None]
            r = [d[v][k]['removed'] for d in D.values()]
            leak = [d[v][k]['est_db'] for d in D.values() if k not in d['_meta']['has']]
            du, _ = delta(D, v, k, 'usdr'); dr, _ = delta(D, v, k, 'removed')
            print(f'| `{v}` | {f2(float(np.mean(u)) if u else None)} | {du} | {np.mean(r):.2f} | {dr} | {f2(float(np.mean(leak)) if leak else None)} |')
        print()

print('# Round 5 tables (generated by r5_summary.py)\n')
print('Variants: see round5.md. Rows that would repeat another row\'s stem exactly are left out of that stem\'s table '
      '(e.g. `hyb6_fix` differs from `hyb6` only in other).\n')
table(ALL, 'Pooled: 26 Cambridge-MT songs')
for s, t in SETS.items():
    if data[s]: table(data[s], f'{s}: {t}')

print('## Paired comparisons, pooled 26 songs (Δ uSDR [95 % CI] items up; for keys and other: items that have the part; '
      '"removed" Δ over all 26 in brackets after)\n')
PAIRS = [('mega_mix', 'hyb6'), ('kim_mega', 'hyb6'), ('mega_mix', 'chain'), ('kim_mega', 'chain'), ('kim_mega', 'mega_mix'),
         ('chain', 'hyb6'), ('mega_mix_keys', 'hyb6'), ('kim_mega_keys', 'hyb6'), ('kim_mega_keys', 'chain'), ('chain+mg', 'chain'),
         ('chain+mgk', 'chain')]
PAIRS = [(a_, b_) for a_, b_ in PAIRS if a_ in vs and b_ in vs]
print('| stem | ' + ' | '.join(f'`{a_}` − `{b_}`' for a_, b_ in PAIRS) + ' |\n|---|' + '---|' * len(PAIRS))
for k in STEMS:
    cells = []
    for a_, b_ in PAIRS:
        du, _ = delta(ALL, a_, k, 'usdr', b_); dr, x = delta(ALL, a_, k, 'removed', b_)
        cells.append(f'{du} ({x.mean():+.2f} removed)' if len(x) and du != 'same stem' and k in ('keys', 'other') else du)
    print(f'| {k} | ' + ' | '.join(cells) + ' |')
print()

print('## Sum-to-mix residual per recipe (dB re the mix)\n')
print('| variant | mean | min | max |\n|---|---|---|---|')
for v in vs:
    r = np.array([d['_resid'][v] for d in ALL.values()])
    if r.max() < -200: print(f'| `{v}` | exact (other = mix − the rest; ≤ {r.max():.0f}) | | |'); continue
    print(f'| `{v}` | {r.mean():.1f} | {r.min():.1f} | {r.max():.1f} |')
print()
print('## Per-item uSDR (main recipes)\n')
MAIN = [v for v in ('hyb6', 'chain', 'mega_mix', 'mega_mix_keys', 'mega_mix_pk', 'kim_mega', 'kim_mega_keys', 'kim_mega_pk') if v in vs]
for k in STEMS:
    print(f'### {k}\n\n| item | {k} dB re mix | ' + ' | '.join(f'`{v}`' for v in MAIN) + ' |\n|---|---|' + '---|' * len(MAIN))
    for i, d in ALL.items():
        if k not in d['_meta']['has']: continue
        print(f'| {i} | {d["_meta"]["stem_db_re_mix"][k]:.1f} | ' + ' | '.join(f2(d[v][k]['usdr']) for v in MAIN) + ' |')
    print()

cf = os.path.join(root, 'cost.jsonl')
if os.path.exists(cf):
    print('## Cost runs (scores/cost.jsonl; CPU = user + sys of the process, s per audio s)\n')
    print('| host | pass | device | threads | input | audio s | CPU-s / audio-s | wall-s / audio-s | Mega long-track rate (per-chunk CPU) | peak RSS GB | GPU mem GB |')
    print('|---|---|---|---|---|---|---|---|---|---|---|')
    for l in open(cf):
        c = json.loads(l)
        print(f"| {c.get('host','')} | {c['pass']} | {c.get('device','cpu')} | {c['threads']} | {c['input']} | {c['audio_s']} | {c['cpu_per_audio_s']} | "
              f"{c['wall_per_audio_s']} | {c.get('mega_rate_long') or '–'} | {c['peak_rss_gb']} | {c.get('gpu_mem_gb') or '–'} |")
    print()

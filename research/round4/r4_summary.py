"""Round 4 tables from data/scores/<set>/<item>.json (r4_score.py).  r4_summary.py [score root] > tables.md
Per set and pooled over sets: mean guitar uSDR, "guitar removed" uSDR, bleed (dB re the estimate's energy), cSDR where
scored; paired Δ vs 6s_s0 per item with a 95 % bootstrap interval over items and items improved.
"""
import glob, json, os, sys
import numpy as np

root = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data/scores')
SETS = ['cmt8', 'cmtx', 'gtechs', 'egdb', 'gset']
NAMES = {'cmt8': 'Cambridge-MT: 8 MUSDB test songs, exact remix', 'cmtx': 'Cambridge-MT: 18 non-MUSDB rock excerpts',
         'gtechs': 'Guitar-TECHS electric over MUSDB backing', 'egdb': 'EGDB-PG electric over MUSDB backing',
         'gset': 'GuitarSet acoustic over MUSDB backing'}
ORDER = ['6s_s0', '6s_s2', '6s_inst', 'mega_mix', 'megaEA_mix', 'mega_inst', 'megaEA_inst',
         'avg(6s_s0,mega_mix)', 'avg(6s_inst,mega_mix)', 'avg(6s_inst,mega_inst)']
rng = np.random.default_rng(0)

def load(s):
    out = {}
    for f in sorted(glob.glob(f'{root}/{s}/*.json')):
        d = json.load(open(f)); out[os.path.basename(f)[:-5]] = d
    return out

def boot(x):
    if len(x) < 2: return (np.nan, np.nan)
    m = [rng.choice(x, len(x)).mean() for _ in range(2000)]; return np.percentile(m, [2.5, 97.5])

data = {s: load(s) for s in SETS}
data = {s: d for s, d in data.items() if d}
print('# Round 4 tables (generated by r4_summary.py)\n')
for s in list(data) + ['pooled (Cambridge-MT)', 'pooled (open sets)']:
    if s.startswith('pooled'):
        ss = ['cmt8', 'cmtx'] if 'Cambridge' in s else ['gtechs', 'egdb', 'gset']
        D = {f'{x}/{k}': v for x in ss if x in data for k, v in data[x].items()}
        title = s
    else:
        D = data[s]; title = f'{s}: {NAMES[s]}'
    if not D: continue
    vs = [v for v in ORDER if all(v in d for d in D.values())]
    if not vs: continue
    secs = sum(d['_meta']['seconds'] for d in D.values())
    print(f'## {title} ({len(D)} items, {secs/60:.1f} min)\n')
    has_c = all('csdr' in d[v] for d in D.values() for v in vs)
    print('| variant | guitar uSDR | Δ vs 6s_s0 [95 % CI] items up | guitar removed uSDR | bleed v+d+b+k | vocals | drums | bass | keys | unexplained |' + (' cSDR | removed cSDR |' if has_c else ''))
    print('|---|---|---|---|---|---|---|---|---|---|' + ('---|---|' if has_c else ''))
    for v in vs:
        u = np.array([d[v]['usdr'] for d in D.values()]); b = np.array([d['6s_s0']['usdr'] for d in D.values()]) if '6s_s0' in vs else None
        dl = u - b if b is not None else None
        lo, hi = boot(dl) if dl is not None else (np.nan, np.nan)
        dtxt = '–' if v == '6s_s0' or dl is None else f'{dl.mean():+.2f} [{lo:+.2f}, {hi:+.2f}] {int((dl > 0).sum())}/{len(dl)}'
        m = lambda k: np.mean([d[v][k] for d in D.values() if k in d[v]]) if any(k in d[v] for d in D.values()) else np.nan
        row = f'| `{v}` | {u.mean():.2f} | {dtxt} | {m("nog_usdr"):.2f} | {m("bleed_vdbk"):.1f} | {m("bleed_vocals"):.1f} | {m("bleed_drums"):.1f} | {m("bleed_bass"):.1f} | {m("bleed_keys"):.1f} | {m("bleed_resid"):.1f} |'
        if has_c: row += f' {m("csdr"):.2f} | {m("csdr_nog"):.2f} |'
        print(row.replace('nan', '–'))
    print()
print('## Per item guitar uSDR\n')
for s, D in data.items():
    vs = [v for v in ORDER if all(v in d for d in D.values())]
    print(f'### {s}\n\n| item | guitar dB re mix | ' + ' | '.join(f'`{v}`' for v in vs) + ' |\n|---|---|' + '---|' * len(vs))
    for k, d in D.items():
        print(f'| {k} | {d["_meta"]["guitar_db_re_mix"]:.1f} | ' + ' | '.join(f'{d[v]["usdr"]:.2f}' for v in vs) + ' |')
    print()
